# -*- coding: utf-8 -*-
"""Generate the frontend upload limit from the backend shared constant.

The generated file keeps the SPA build free of Python at runtime while giving
the 50MB fact one owner. ``--check`` fails when the generated file is stale.
"""

import argparse
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BACKEND = os.path.join(REPO_ROOT, "backend")
TARGET = os.path.join(REPO_ROOT, "frontend", "src", "api", "uploadLimits.ts")
if BACKEND not in sys.path:
    sys.path.insert(0, BACKEND)

from shared.upload_limits import (  # noqa: E402
    MAX_UPLOAD_BYTES,
    MAX_UPLOAD_MEGABYTES,
    MODEL_3D_EXTENSIONS,
)


def render():
    extensions = ", ".join('"%s"' % extension for extension in MODEL_3D_EXTENSIONS)
    return (
        "// Generated by tools/sync_upload_limit.py from backend/shared/upload_limits.py.\n"
        "// Do not edit by hand.\n"
        "export const MAX_UPLOAD_BYTES = %d;\n"
        "export const MAX_UPLOAD_MEGABYTES = %d;\n"
        "export const MODEL_3D_EXTENSIONS = [%s] as const;\n"
        % (MAX_UPLOAD_BYTES, MAX_UPLOAD_MEGABYTES, extensions)
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        try:
            with open(TARGET, "rb") as handle:
                actual = handle.read()
        except OSError:
            actual = b""
        # Git may check the generated file out with CRLF on Windows. Line
        # endings are not part of the generated contract.
        actual = actual.replace(b"\r\n", b"\n")
        if actual != expected.encode("utf-8"):
            print("frontend upload limit is stale; run python tools/sync_upload_limit.py",
                  file=sys.stderr)
            return 1
        return 0
    with open(TARGET, "wb") as handle:
        handle.write(expected.encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
