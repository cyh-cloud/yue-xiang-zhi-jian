def _parse_date(s):
    import datetime as _dt
    try:
        return _dt.date.fromisoformat((s or "").strip())
    except Exception:
        return None


def _with_status(entry, today=None):
    """为一条公告补上报名状态（open / upcoming / closed / unknown）与剩余天数。"""
    import copy
    import datetime as _dt
    today = today or _dt.date.today()
    d = copy.deepcopy(entry)
    start = _parse_date(entry.get("signup_start"))
    end = _parse_date(entry.get("deadline"))
    if not end:
        st = "unknown"
    elif today > end:
        st = "closed"
    elif start and today < start:
        st = "upcoming"
    else:
        st = "open"
    d["status"] = st
    d["status_label"] = STATUS_LABEL.get(st, "详见公告")
    d["days_left"] = (end - today).days if (end and st in ("open", "upcoming")) else None
    d["starts_in"] = (start - today).days if (start and st == "upcoming") else None
    return d


def get_recruitment_list(today=None):
    """返回全部公开招聘公告（含报名状态）。默认按「报名中 → 即将开始 → 已过期」排序。"""
    items = [_with_status(e, today) for e in RECRUIT_DATA]
    order = {"open": 0, "upcoming": 1, "unknown": 2, "closed": 3}
    items.sort(key=lambda x: (order.get(x["status"], 9), x.get("deadline") or "9999-99-99"))
    return items


def get_recruitment(key):
    """按 key 取单条公告（含报名状态）。"""
    for e in RECRUIT_DATA:
        if e.get("key") == key:
            return _with_status(e)
    return None


