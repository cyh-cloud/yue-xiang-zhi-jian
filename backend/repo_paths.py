# -*- coding: utf-8 -*-
"""文件系统路径的唯一基准：仓库根。

上传落盘目录、数据库目录、静态资源根目录、环境变量文件位置全部从这里推导，
不再以各自模块文件所在目录为基准。后端按领域拆分时模块会搬进子目录，
若路径跟着模块的 `__file__` 走，上传目录与静态资源放行目录会指向不同位置，
结果是文件存得下却取不回。

后端代码整体迁入 backend/ 后，本模块也跟着搬了进去。data/、uploads/、.env
都仍在仓库根，所以这里要从 `__file__` 上跳一级：__file__ 的上级是 backend/，
再上级才是仓库根。写成 parents[1] 而不是写死绝对路径，是为了让整个仓库
可以整体拷贝到别处。

本模块只依赖标准库 os，不 import 仓库内任何其他模块：谁都能 import 它，
且不会与业务模块形成环。环境变量仍是唯一配置入口，可调项继续在各自模块
从环境变量读取，默认值内聚在模块里。
"""

import os

# 本文件位于 backend/ 下，它的上级目录的上级才是仓库根。
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# 环境变量文件固定在仓库根下读取，保证「改完重启生效」不随启动目录漂移。
ENV_FILE = os.path.join(REPO_ROOT, '.env')
