mapping = {}
for tid, title, build, criteria in TICKETS:
    path = os.path.join(BODY_DIR, tid + '.md')
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(ticket(tid, title, build, criteria))
    proc = subprocess.run(['gh', 'issue', 'create', '--title', title,
                           '--body-file', path, '--label', 'ready-for-agent'],
                          capture_output=True, text=True, encoding='utf-8')
    if proc.returncode != 0:
        print('FAILED', tid, proc.stderr.strip())
        sys.exit(1)
    url = proc.stdout.strip()
    num = int(url.rstrip('/').split('/')[-1])
    mapping[tid] = num
    print('%s -> #%d' % (tid, num))

with open(os.path.join('.scratch', 'backend-split', 'ticket-map.json'), 'w', encoding='utf-8') as fh:
    json.dump(mapping, fh, ensure_ascii=False, indent=2)
print('---MAP---')
for k, v in mapping.items():
    print('%s=%d' % (k, v))
